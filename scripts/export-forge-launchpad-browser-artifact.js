const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const artifactPath = path.join(
  root,
  'artifacts',
  'contracts',
  'launchpad',
  'ForgeLaunchpadBootstrap.sol',
  'ForgeLaunchpadBootstrap.json'
);
const outputPath = path.join(root, 'lib', 'forge-launchpad-bootstrap-artifact.js');

if (!fs.existsSync(artifactPath)) {
  throw new Error(`Missing compiled ForgeLaunchpadBootstrap artifact: ${artifactPath}`);
}

const artifact = JSON.parse(fs.readFileSync(artifactPath, 'utf8'));
if (artifact.contractName !== 'ForgeLaunchpadBootstrap') {
  throw new Error(`Unexpected contract artifact: ${artifact.contractName || 'unknown'}`);
}
if (!Array.isArray(artifact.abi) || typeof artifact.bytecode !== 'string' || !artifact.bytecode.startsWith('0x')) {
  throw new Error('ForgeLaunchpadBootstrap artifact is missing ABI or deployment bytecode.');
}

const bytecodeBytes = (artifact.bytecode.length - 2) / 2;
if (bytecodeBytes <= 0 || bytecodeBytes > 49152) {
  throw new Error(`ForgeLaunchpadBootstrap init code is outside the EIP-3860 limit: ${bytecodeBytes} bytes`);
}

const output = `// AUTO-GENERATED by scripts/export-forge-launchpad-browser-artifact.js\n// Source: ${artifact.sourceName}\n// Compiler: Solidity 0.8.26 / optimizer 200 / Cancun (hardhat.config.js)\n// Do not hand-edit. Regenerate after contract changes.\n\nexport const FORGE_LAUNCHPAD_BOOTSTRAP_ABI = ${JSON.stringify(artifact.abi, null, 2)};\n\nexport const FORGE_LAUNCHPAD_BOOTSTRAP_BYTECODE = ${JSON.stringify(artifact.bytecode)};\n\nexport const FORGE_LAUNCHPAD_BOOTSTRAP_BYTECODE_BYTES = ${bytecodeBytes};\nexport const FORGE_LAUNCHPAD_BOOTSTRAP_SOURCE = ${JSON.stringify(artifact.sourceName)};\n\nexport default {\n  abi: FORGE_LAUNCHPAD_BOOTSTRAP_ABI,\n  bytecode: FORGE_LAUNCHPAD_BOOTSTRAP_BYTECODE,\n  bytecodeBytes: FORGE_LAUNCHPAD_BOOTSTRAP_BYTECODE_BYTES,\n  source: FORGE_LAUNCHPAD_BOOTSTRAP_SOURCE,\n};\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(`Wrote ${path.relative(root, outputPath)} (${bytecodeBytes} deployment bytes)`);
